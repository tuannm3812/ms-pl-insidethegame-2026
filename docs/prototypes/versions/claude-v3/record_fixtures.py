"""Record the offline API replies for Claude v3.

Run from the repository root at the recorded revision:
``python docs/prototypes/versions/claude-v3/record_fixtures.py``. It uses
the rule-based agents only (no model). Unlike v2 there is no prototype-only
data: v3 is the app's own page, so every field comes from the API.

The 60' check depends on each call's decision. The rules verifier treats
each call on its own, so the check is recorded per call and decision state
and ``offline.js`` puts a reply together from the three parts. A state is
``option:status:implemented``, e.g. ``a:adopted:1`` or ``-:rejected:0``.
"""

import json
import pathlib
import sys
from urllib.parse import urlencode

sys.path.insert(0, str(pathlib.Path.cwd()))

from fastapi.testclient import TestClient  # noqa: E402

import app as app_module  # noqa: E402

OUT = pathlib.Path(__file__).with_name("fixtures.js")
LANGUAGES = ("en", "es", "vi", "fr", "ar")
FINDINGS = ("press", "threat", "scoreline")
STATES = [(None, s, False) for s in ("open", "deferred", "rejected")] + [
    (o, s, i)
    for o in ("a", "b")
    for s, i in (
        ("open", False),
        ("deferred", False),
        ("rejected", False),
        ("adopted", False),
        ("adopted", True),
    )
]


def key(option: str | None, status: str, implemented: bool) -> str:
    """The state key offline.js builds from a decision."""
    return f"{option or '-'}:{status}:{int(implemented)}"


def main() -> None:
    """Write fixtures.js: every GET reply and the check parts per state."""
    app_module.client = None
    c = TestClient(app_module.app)
    meta = c.get("/api/match").json()
    fx: dict[str, object] = {
        "api/match": meta,
        "api/health": c.get("/api/health").json(),
        "api/events?half=1": c.get("/api/events?half=1").json(),
    }
    for focus in ("home", "away"):
        q = urlencode({"mode": "analyst", "focus": focus, "language": "en"})
        brief = c.get("/api/briefing?" + q).json()
        fx["api/briefing?" + q] = brief
        body = {
            "focus": focus,
            "findings": brief["findings"],
            "changes": brief["changes"],
        }
        per: dict[str, dict] = {f: {} for f in FINDINGS}
        common = None
        for option, status, implemented in STATES:
            decisions = {
                f: {
                    "option": option,
                    "status": status,
                    "implemented": implemented,
                }
                for f in FINDINGS
            }
            r = c.post("/api/check", json=body | {"decisions": decisions})
            r.raise_for_status()
            out = r.json()
            for i, f in enumerate(FINDINGS):
                per[f][key(option, status, implemented)] = {
                    "check": out["checks"][i],
                    "verdict": out["verdicts"][i],
                    "choice": out["choices"][f],
                    "decision": out["decisions"][f],
                }
            if common is None:
                common = {
                    k: v
                    for k, v in out.items()
                    if k not in ("checks", "verdicts", "choices", "decisions")
                }
        fx[f"check:{focus}"] = {"common": common, "per": per}
        # The page defaults a fan to the tenth player of the focus squad.
        player = meta["teams"][focus]["players"][9]["name"]
        for lang in LANGUAGES:
            q = urlencode(
                {
                    "mode": "fan",
                    "focus": focus,
                    "language": lang,
                    "player": player,
                }
            )
            fx["api/briefing?" + q] = c.get("/api/briefing?" + q).json()
    OUT.write_text(
        "// Recorded offline API replies, seed 27. Generated by "
        "record_fixtures.py (Claude v3); do not edit.\n"
        "window.FIXTURES = " + json.dumps(fx, separators=(",", ":")) + ";\n"
    )
    print(f"{len(fx)} entries -> {OUT}")


if __name__ == "__main__":
    main()
